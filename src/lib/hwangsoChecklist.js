/** 'C01|개념|01' 한 줄을 다루기 쉬운 객체로 편다. */
export function parseChecklistItem(unit, index) {
  const [concept, type, item] = String(unit.items[index]).split('|');
  return {
    no: index + 1,
    code: buildItemCode(unit.id, index + 1),
    unitId: unit.id,
    concept,
    conceptTitle: unit.concepts.find((c) => c.code === concept)?.title ?? '',
    type,
    item,
    // 아이 화면에 보여줄 이름. 예) '확인 12'
    label: `${type} ${item}`,
  };
}

/**
 * 체크리스트 문항의 고유 코드.
 * 학습기록 시트의 '콘텐츠 코드' 자리에 그대로 들어가므로, 나중에 문제 이미지를 붙일 때도
 * 이 코드를 파일명으로 쓰면 기존 채점 흐름과 자연스럽게 이어진다.
 * 예) HS_M2A1_001
 */
export function buildItemCode(unitId, no) {
  return `HS_${unitId}_${String(no).padStart(3, '0')}`;
}

export function getUnit(unitId) {
  return CHECKLIST_UNITS.find((u) => u.id === unitId) ?? null;
}

/** 한 단원의 모든 문항을 펼쳐서 돌려준다. */
export function listUnitItems(unitId) {
  const unit = getUnit(unitId);
  if (!unit) return [];
  return unit.items.map((_, i) => parseChecklistItem(unit, i));
}

/** 개념(C01…)별로 묶어서 돌려준다. 체크리스트 표를 개념 단위로 접었다 펴는 데 쓴다. */
export function groupUnitByConcept(unitId) {
  const unit = getUnit(unitId);
  if (!unit) return [];
  const items = listUnitItems(unitId);
  return unit.concepts.map((c) => ({
    ...c,
    items: items.filter((it) => it.concept === c.code),
  }));
}

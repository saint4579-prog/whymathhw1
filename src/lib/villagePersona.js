/** 캐릭터를 클릭했을 때 나올 대사 하나 */
export function pickLine(name, random = Math.random) {
  const own = NAME_LINES[name];
  const byType = TYPE_LINES[mbtiOf(name)] ?? TYPE_LINES.ENFP;
  // 이름 전용 대사가 있으면 그쪽을 더 자주 쓴다. 캐릭터다움이 살아나도록.
  const pool = own ? [...own, ...own, ...byType] : byType;
  return pool[Math.floor(random() * pool.length) % pool.length];
}

/**
 * 두 캐릭터가 가까워졌을 때 주고받는 말.
 * E가 다가가면 I는 놀라고, T는 사실을, F는 감정을, J는 계획을, P는 핑계를 말한다.
 */
export function pickGreeting(fromName, toName, random = Math.random) {
  const from = mbtiOf(fromName);
  const to = mbtiOf(toName);

  const openers = [];
  if (isExtrovert(from) && !isExtrovert(to)) {
    openers.push({ a: `${toName}! 반가워! 같이 놀자!`, b: '까, 깜짝이야... 조금만 조용히...' });
  } else if (!isExtrovert(from) && isExtrovert(to)) {
    openers.push({ a: '...안녕.', b: `오! ${fromName} 안녕! 오늘 기분 어때?!` });
  } else if (isExtrovert(from)) {
    openers.push({ a: '야호! 우리 오늘 뭐 하고 놀까?', b: '좋아 좋아! 신난다!' });
  } else {
    openers.push({ a: '...안녕.', b: '...응, 안녕.' });
  }

  if (isFeeler(from) !== isFeeler(to)) {
    openers.push(
      isFeeler(from)
        ? { a: '오늘 좀 속상한 일이 있었어...', b: '음, 원인이 뭔데? 해결책부터 찾아보자.' }
        : { a: '그건 네가 계획을 안 세워서 그래.', b: '으앙, 그래도 위로부터 해주면 안 돼...?' }
    );
  }

  if (isJudger(from) !== isJudger(to)) {
    openers.push(
      isJudger(from)
        ? { a: '오늘 할 일 목록은 다 확인했지?', b: '어... 그건 이따가 생각하려고 했는데, 헤헤.' }
        : { a: '오늘은 그냥 흘러가는 대로 가볼래!', b: '안 돼. 순서를 정해두는 게 훨씬 나아.' }
    );
  }

  return openers[Math.floor(random() * openers.length) % openers.length];
}

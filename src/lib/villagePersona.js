const TYPE_LIST = Object.keys(MBTI_TYPES);

// 이름을 숫자로 바꾼다. 같은 이름이면 언제나 같은 값이 나온다.
function seedOf(name) {
  let seed = 0;
  for (const ch of String(name)) seed = (seed * 31 + ch.charCodeAt(0)) % 100000;
  return seed;
}

export function mbtiOf(name) {
  return NAME_TO_MBTI[name] ?? TYPE_LIST[seedOf(name) % TYPE_LIST.length];
}

export const isExtrovert = (type) => String(type).startsWith('E');
export const isFeeler = (type) => String(type)[2] === 'F';
export const isJudger = (type) => String(type)[3] === 'J';

